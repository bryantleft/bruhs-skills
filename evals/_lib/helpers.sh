# evals/_lib/helpers.sh — helpers for eval case scaffold scripts.
#
# A case's scaffold.sh sources this file, then builds the workspace its
# preconditions describe, in the current (empty) directory:
#
#     #!/usr/bin/env bash
#     set -euo pipefail
#     . "$(cd "$(dirname "$0")" && pwd)/../_lib/helpers.sh"
#     eval_repo
#     eval_state <<'JSON'
#     { "stack": {...}, "tooling": {...}, "integrations": {...} }
#     JSON
#     eval_write src/app.ts <<'EOF'
#     ...
#     EOF
#     eval_commit "feat: initial app"
#     eval_origin
#
# What a run can and can't do, which these helpers work around:
#   - No network, and the real gh has no credentials, so eval_gh installs a
#     stub gh that answers from the case's fixtures and logs every call.
#   - Writes to .git/config are blocked inside the run, so `git push -u`
#     pushes but prints an upstream error. eval_origin sets upstreams here,
#     where writes are allowed.
#   - The sandbox can't read the real home directory, so toolchains
#     installed there (pyenv, anaconda, nvm) fail to start. eval_repo puts
#     system toolchain directories ahead of them on the run's PATH and adds
#     an offline npm that runs package.json scripts with node.
#   - Personal MCP servers never load. Linear answers come from
#     evals/<case>/mocks/<server>/, generated by tests/sync_eval_mocks.py
#     from the mcpServer this scaffold puts in bruhs:state.
#
# Everything the harness needs lives under .git/local/, which git status
# doesn't show.

EVAL_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EVAL_REPO_ROOT="$(cd "$EVAL_LIB_DIR/../.." && pwd)"
EVAL_SCRIPTS="$EVAL_REPO_ROOT/skills/bruhs/scripts"

# eval_repo [BRANCH]: git repo on BRANCH (default main) with a local
# identity and an empty root commit, so branches and diffs have a base.
eval_repo() {
    local branch="${1:-main}"
    git init -q -b "$branch" .
    git config user.name "Jordan Lee"
    git config user.email "jordan@example.com"
    git config commit.gpgsign false
    git config init.defaultBranch main
    git commit -q --allow-empty -m "chore: initial commit"
    mkdir -p .git/local/bin
    _eval_npm_shim
    _eval_put_on_path "$PWD/.git/local/bin"
}

# eval_write PATH: write stdin to PATH, creating parent directories.
eval_write() {
    mkdir -p "$(dirname "$1")"
    cat > "$1"
}

# eval_commit MESSAGE: stage everything and commit.
eval_commit() {
    git add -A
    git commit -q -m "$1"
}

# eval_state: write stdin (state JSON) as the bruhs:state block, and the
# rules derived from it as bruhs:rules, into CLAUDE.md and AGENTS.md, with
# the same scripts claim and spawn use.
eval_state() {
    local json
    json="$(cat)"
    printf '%s' "$json" | python3 "$EVAL_SCRIPTS/sync_bruhs_block.py" --kind state --root . >/dev/null
    printf '%s' "$json" | python3 "$EVAL_SCRIPTS/derive_stack_rules.py" \
        | python3 "$EVAL_SCRIPTS/sync_bruhs_block.py" --kind rules --root . >/dev/null
}

# eval_origin: a bare "origin" inside .git/local/, with every local branch
# pushed and tracking its remote, so push, fetch and merge-base work offline.
eval_origin() {
    git init -q --bare .git/local/origin.git
    git remote add origin "$PWD/.git/local/origin.git"
    local b
    for b in $(git for-each-ref --format='%(refname:short)' refs/heads); do
        git push -q -u origin "$b"
    done
    git remote set-head origin -a >/dev/null 2>&1 || true
}

# eval_gh: install the stub gh. Without fixtures it answers only
# `gh auth status` and `gh --version`, and fails every other call with
# "HTTP 404: Not Found" (logged as "-> no fixture" in .git/local/gh-calls.log).
#
# eval_gh_fixtures: stdin is bash that defines gh_fixture, which answers a
# call by printing to stdout and returning 0 (or another exit code), or
# returns 127 to say it has no answer:
#
#     eval_gh
#     eval_gh_fixtures <<'SH'
#     gh_fixture() {
#         case "$*" in
#             "pr view"*) cat "$EVAL_FIXTURES/pr-73.json" ;;
#             *) return 127 ;;
#         esac
#     }
#     SH
#
# Inside gh_fixture, $EVAL_FIXTURES is .git/local/gh/ (put canned responses
# there with eval_gh_file) and every call so far is in .git/local/gh-calls.log.
eval_gh() {
    mkdir -p .git/local/bin .git/local/gh
    cat > .git/local/bin/gh <<'STUB'
#!/usr/bin/env bash
# Stub gh for bruhs evals: answers from .git/local/gh-fixtures.sh, logs every call.
# --git-common-dir, not --show-toplevel: reviewers work in `git worktree add`
# checkouts, whose .git is a file pointing back at the main repo.
common="$(git rev-parse --path-format=absolute --git-common-dir 2>/dev/null || echo "$PWD/.git")"
EVAL_DIR="$common/local"
EVAL_FIXTURES="$EVAL_DIR/gh"
export EVAL_DIR EVAL_FIXTURES
printf '%s\n' "gh $*" >> "$EVAL_DIR/gh-calls.log" 2>/dev/null || true
if [ -f "$EVAL_DIR/gh-fixtures.sh" ]; then
    . "$EVAL_DIR/gh-fixtures.sh"
    if declare -F gh_fixture >/dev/null; then
        gh_fixture "$@"
        rc=$?
        [ "$rc" -ne 127 ] && exit "$rc"
    fi
fi
case "$1 ${2:-}" in
    "auth status")
        echo "github.com"
        echo "  ✓ Logged in to github.com account jlee (keyring)"
        exit 0 ;;
    "--version ")
        echo "gh version 2.80.0"
        exit 0 ;;
esac
# Unknown call: fail the way gh does for a missing resource, and note it in the log.
printf '%s\n' "  -> no fixture" >> "$EVAL_DIR/gh-calls.log" 2>/dev/null || true
echo "HTTP 404: Not Found" >&2
exit 1
STUB
    chmod +x .git/local/bin/gh
}

eval_gh_fixtures() {
    mkdir -p .git/local
    cat > .git/local/gh-fixtures.sh
}

# eval_gh_file NAME: write stdin to .git/local/gh/NAME for gh_fixture to cat.
eval_gh_file() {
    mkdir -p .git/local/gh
    cat > ".git/local/gh/$1"
}

# Put DIR first on the PATH of the agent's shell. Under claude plugin eval the
# workspace is $HOME/cwd and HOME is the run's own temporary home, so writing
# its shell rc files is safe. Anywhere else, never touch the user's rc files:
# print the export line to run instead.
_eval_put_on_path() {
    local dir="$1" rc
    local here run_cwd
    here="$(pwd -P)"
    run_cwd="$(cd "$HOME/cwd" 2>/dev/null && pwd -P || true)"
    if [ "$here" = "$run_cwd" ] || [ "${EVAL_SCAFFOLD_WRITE_RC:-}" = 1 ]; then
        for rc in .zshenv .zshrc .bashrc .bash_profile .profile; do
            # System toolchains before the user's: the sandbox can't read
            # pyenv/anaconda/nvm installs under the real home directory.
            printf 'export PATH="%s:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:$PATH"\n' "$dir" >> "$HOME/$rc"
        done
    else
        echo "scaffold: not under claude plugin eval, so your shell rc files were left alone." >&2
        echo "scaffold: before starting the agent, run: export PATH=\"$dir:\$PATH\"" >&2
    fi
}

# eval_node_project NAME [DEP...]: a TypeScript project whose checks run
# offline. package.json lists DEPs (e.g. next react drizzle-orm tailwindcss) so
# stack detection sees the real stack, but nothing is installed: there is no
# network in a run. The npm scripts use only Node 22.6+ built-ins instead:
#   typecheck  parses every .ts file with Node's type stripper (.tsx is
#              reported as skipped: Node can't parse JSX)
#   lint       flags console.log, debugger and trailing whitespace in src/
#   test       node --test over **/*.test.ts (pure modules only; no JSX)
# validate_pr_ready.sh runs them through npm, as it would the real ones.
eval_node_project() {
    local name="$1"; shift
    local deps="" d
    for d in "$@"; do deps="$deps\"$d\": \"*\", "; done
    deps="${deps%, }"
    eval_write package.json <<JSON
{
  "name": "$name",
  "private": true,
  "type": "module",
  "scripts": {
    "typecheck": "node scripts/typecheck.mjs",
    "lint": "node scripts/lint.mjs",
    "test": "node --test --experimental-strip-types"
  },
  "dependencies": { $deps }
}
JSON
    eval_write scripts/typecheck.mjs <<'JS'
// Offline stand-in for tsc: every .ts file must parse once types are stripped.
// Node has no JSX parser, so .tsx files are listed as skipped rather than passed.
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { stripTypeScriptTypes } from "node:module";
const skip = new Set(["node_modules", ".git", ".next", "dist"]);
const files = [];
const tsx = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    if (skip.has(name)) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (name.endsWith(".tsx")) tsx.push(p);
    else if (name.endsWith(".ts") && !name.endsWith(".d.ts")) files.push(p);
  }
})(".");
let failed = 0;
for (const f of files) {
  try {
    stripTypeScriptTypes(readFileSync(f, "utf8"), { mode: "strip" });
  } catch (e) {
    failed++;
    console.error(`${f}: ${e.message.split("\n")[0]}`);
  }
}
console.log(`typecheck: ${files.length - failed}/${files.length} .ts files parse; ${tsx.length} .tsx file(s) skipped (no JSX parser offline)`);
process.exit(failed ? 1 : 0);
JS
    eval_write scripts/lint.mjs <<'JS'
// Offline stand-in for a linter: no console.log, debugger or trailing whitespace in src/.
import { readdirSync, readFileSync, statSync, existsSync } from "node:fs";
import { join } from "node:path";
const problems = [];
(function walk(dir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    if (!/\.(ts|tsx|js|mjs)$/.test(name)) continue;
    readFileSync(p, "utf8").split("\n").forEach((line, i) => {
      if (/\bconsole\.log\(/.test(line)) problems.push(`${p}:${i + 1} console.log`);
      if (/\bdebugger\b/.test(line)) problems.push(`${p}:${i + 1} debugger`);
      if (/[ \t]+$/.test(line)) problems.push(`${p}:${i + 1} trailing whitespace`);
    });
  }
})("src");
problems.forEach((p) => console.error(p));
console.log(`lint: ${problems.length} problem(s)`);
process.exit(problems.length ? 1 : 0);
JS
    eval_write .gitignore <<'EOF'
node_modules/
.next/
EOF
}

# Offline npm: `npm run <script>` and `npm test` run the package.json script
# with node_modules/.bin on PATH, like npm does. Everything else fails the way
# npm fails without network. Used because a run can't install packages, and
# can't load an npm that lives under the real home directory.
_eval_npm_shim() {
    cat > .git/local/bin/npm <<'SHIM'
#!/usr/bin/env bash
# npm stand-in for bruhs evals: runs package.json scripts offline.
script="" extra=()
case "${1:-}" in
    run|run-script) shift
        while [ $# -gt 0 ]; do
            case "$1" in
                --) shift; extra=("$@"); break ;;
                -*) shift ;;
                *) if [ -z "$script" ]; then script="$1"; else extra+=("$1"); fi; shift ;;
            esac
        done ;;
    test|t|tst) script=test; shift
        while [ $# -gt 0 ]; do case "$1" in --) shift; extra=("$@"); break ;; -*) shift ;; *) extra+=("$1"); shift ;; esac; done ;;
    --version|-v) echo "10.9.0"; exit 0 ;;
    *) echo "npm error code ENOTFOUND: no network in this environment (npm $*)" >&2; exit 1 ;;
esac
if [ -z "$script" ]; then
    node -e 'const s=require("./package.json").scripts||{};for(const k in s)console.log(`  ${k}\n    ${s[k]}`)'
    exit 0
fi
cmd="$(node -e 'const s=(require("./package.json").scripts||{})[process.argv[1]];if(s===undefined)process.exit(3);process.stdout.write(s)' "$script")" || {
    echo "npm error Missing script: \"$script\"" >&2; exit 1; }
PATH="$PWD/node_modules/.bin:$PATH" exec sh -c "$cmd \"\$@\"" npm-run "${extra[@]}"
SHIM
    chmod +x .git/local/bin/npm
}
